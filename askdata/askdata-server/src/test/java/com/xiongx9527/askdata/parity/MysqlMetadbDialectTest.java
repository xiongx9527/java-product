/**
 * A9：MySQL 方言验证（真实 MySQL 8 实例）。
 *
 * <p>在临时 schema 上执行 MySQL baseline + common 种子，验证脚本可从空库完整执行；
 * 同时静态校验 MySQL 方言差异（utf8mb4/LONGTEXT/无 ANSI 时间字面量），
 * 避免把 PostgreSQL 语法误放进 MySQL baseline。</p>
 */
class MysqlMetadbDialectTest {

    private static final Path MYSQL_BASELINE =
            Paths.get("src/main/resources/db/migration/mysql/V1__baseline.sql");

    private static final Path COMMON_SEED =
            Paths.get("src/main/resources/db/migration/common/V2__seed.sql");

    @Test
    void mysqlBaselineRunsFromEmptyDatabaseAndWritesSeed() {
        JdbcTemplate jdbc = MysqlTestSupport.createSchema();
        assertEquals(37, tableCount(jdbc));
        assertEquals(1, count(jdbc, "sys_user"));
        assertEquals(12, count(jdbc, "sys_arg"));
        assertEquals(3, count(jdbc, "system_variable"));
        assertEquals(19, count(jdbc, "core_field"));
        assertEquals(Lists.of("1", "2", "3", "4", "5"), versions(jdbc));
    }

    @Test
    void mysqlBaselineKeepsDialectSpecificSyntax() throws Exception {
        String sql = Io.readAllUtf8(Files.newInputStream(MYSQL_BASELINE));
        assertEquals(35, countMatches(Pattern.compile("CREATE TABLE"), sql));
        assertTrue(sql.contains(") DEFAULT CHARSET=utf8mb4;"),
                "MySQL baseline 每张表应声明 utf8mb4 字符集");
        assertTrue(sql.contains("LONGTEXT"), "MySQL 大文本列应使用 LONGTEXT");
        assertFalse(sql.contains("TIMESTAMP '"), "MySQL baseline 不应使用 ANSI 时间字面量");
        assertFalse(sql.contains("GENERATED BY DEFAULT AS IDENTITY"),
                "MySQL 不应复用 PostgreSQL 的 identity 语法");
        assertTrue(Files.exists(COMMON_SEED), "种子必须放在 common，供三种方言共享");
        assertFalse(Files.exists(Paths.get("src/main/resources/db/migration/common/V1__baseline.sql")),
                "baseline 必须按方言拆分，不能放回 common");
    }

    private int tableCount(JdbcTemplate jdbc) {
        Integer count = jdbc.queryForObject(
                "SELECT COUNT(*) FROM information_schema.tables "
                        + "WHERE table_schema = DATABASE() AND table_name <> 'flyway_schema_history'",
                Integer.class);
        return count == null ? 0 : count;
    }

    private int count(JdbcTemplate jdbc, String table) {
        Integer count = jdbc.queryForObject("SELECT COUNT(*) FROM " + table, Integer.class);
        return count == null ? 0 : count;
    }

    private List<String> versions(JdbcTemplate jdbc) {
        return jdbc.queryForList(
                "SELECT version FROM flyway_schema_history WHERE success = 1 AND version IS NOT NULL "
                        + "ORDER BY installed_rank", String.class);
    }

    /** 统计正则命中次数（Java 8 无 Matcher.results()）。 */
    private static long countMatches(java.util.regex.Pattern pattern, String text) {
        java.util.regex.Matcher m = pattern.matcher(text);
        long count = 0;
        while (m.find()) {
            count++;
        }
        return count;
    }
}
