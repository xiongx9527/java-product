import { chromium } from 'playwright';
const BASE='http://127.0.0.1:8000';
const b=await chromium.launch({channel:'chrome',args:['--no-proxy-server']});
const p=await b.newPage({viewport:{width:1440,height:900}});
p.on('request',r=>{if(r.url().includes('aimodel'))console.log('REQ',r.method(),r.url().replace(BASE,''));});
await p.goto(BASE+'/#/login');
await p.locator('.login-form input').first().waitFor();
await p.locator('.login-form input').first().fill('admin');
await p.locator('.login-form input[type=password]').fill('SQLBot@123456');
await p.locator('button.login-btn').click();
await p.waitForURL(/\/#\/chat/,{timeout:20000});
await p.goto(BASE+'/#/system/model');
await p.waitForTimeout(2000);
const card = p.locator('.model-config .card', { hasText: 'e2e-probe-default' }).first();
await card.locator('.more').click();
await p.waitForTimeout(600);
await card.locator('.popover-card_workspace .item', { hasText: '删除' }).first().click();
await p.waitForTimeout(800);
const btn = p.locator('.ed-message-box__btns button:visible').filter({ hasText: /删除/ }).first();
console.log('btn count', await p.locator('.ed-message-box__btns button:visible').filter({hasText:/删除/}).count());
await btn.click();
await p.waitForTimeout(2500);
console.log('after click cards', await p.locator('.model-config .card').count());
await b.close();
